    def __init__(self, client: Optional[FlorenceClient] = None, model_id: str = "microsoft/Florence-2-base") -> None:
        """Initialize the tag extractor.
        
        Args:
            client: Pre-instantiated FlorenceClient or None.
            model_id: HuggingFace model ID to initialize if client is None.
        """
        self.model_id = model_id
        self._client = client

    @property
    def client(self) -> FlorenceClient:
        """Lazy-load the FlorenceClient to avoid premature VRAM allocation."""
        if self._client is None:
            self._client = FlorenceClient(model_id=self.model_id)
        return self._client

    def extract_tags(
        self,
        image: Union[str, Path, Image.Image],
        ocr_task: bool = True,
    ) -> ProductVisualAttributes:
        """Execute Florence-2 inference and normalize extracted features.
        
        Args:
            image: Image path or PIL Image instance.
            ocr_task: Whether to run an explicit OCR pass.
            
        Returns:
            Structured ProductVisualAttributes instance.
        """
        raw_outputs: Dict[str, Any] = {}

        # 1. Detailed visual description
        caption_res = self.client.run_task(image, FlorenceClient.TASK_MORE_DETAILED_CAPTION)
        if isinstance(caption_res, dict):
            detailed_caption = caption_res.get(FlorenceClient.TASK_MORE_DETAILED_CAPTION, "")
            if isinstance(detailed_caption, dict) and "labels" in detailed_caption:
                detailed_caption = " ".join(detailed_caption["labels"])
        else:
            detailed_caption = str(caption_res)
        raw_outputs["caption"] = detailed_caption

        # 2. OCR text extraction
        detected_text_list: List[str] = []
        if ocr_task:
            try:
                ocr_res = self.client.run_task(image, FlorenceClient.TASK_OCR)
                if isinstance(ocr_res, dict):
                    ocr_val = ocr_res.get(FlorenceClient.TASK_OCR, "")
                else:
                    ocr_val = ocr_res
                raw_outputs["ocr"] = ocr_val

                if isinstance(ocr_val, dict) and "labels" in ocr_val:
                    detected_text_list = [str(lbl).strip() for lbl in ocr_val["labels"] if len(str(lbl).strip()) > 1]
                elif isinstance(ocr_val, str):
                    detected_text_list = [
                        line.strip()
                        for line in ocr_val.split("\n")
                        if len(line.strip()) > 1
                    ]
            except Exception as e:
                logger.warning(f"OCR task failed: {e}")
                raw_outputs["ocr_error"] = str(e)

        # 3. Parse taxonomy and attributes prioritizing OCR text & packaging container
        parsed = self._parse_attributes_from_text(
            detailed_caption=detailed_caption,
            detected_text=detected_text_list,
            raw_outputs=raw_outputs,
        )

        return parsed

    def _parse_attributes_from_text(
        self,
        detailed_caption: str,
        detected_text: List[str],
        raw_outputs: Dict[str, Any],
    ) -> ProductVisualAttributes:
        """Extract categories, colors, materials, and tags from caption and OCR."""
        ocr_combined = " ".join(detected_text).lower()
        caption_lower = detailed_caption.lower()
        full_text = f"{ocr_combined} {caption_lower}"

        # 1. Detect if physical object is a packaged container
        is_packaged_container, container_type = self._detect_container(caption_lower, ocr_combined)

        # 2. Classify Category & Product Type with Layer 1 Priority Registry & Layer 2 Weighted Scoring
        category, product_type, priority_materials = self._classify_category_and_type(
            ocr_text=ocr_combined,
            caption=caption_lower,
            is_container=is_packaged_container,
            container_type=container_type,
        )

        # 3. Extract Dominant Colors
        detected_colors: List[str] = []
        for color in self.KNOWN_COLORS:
            if re.search(rf"\b{re.escape(color)}\b", full_text):
                title_color = color.title()
                if title_color not in detected_colors:
                    detected_colors.append(title_color)

        # 4. Extract Materials (prioritize Layer 1 / Layer 2 materials, then container, then keyword scan)
        detected_materials: List[str] = list(priority_materials) if priority_materials else []
        if not detected_materials:
            if is_packaged_container and container_type:
                if container_type in ("tin", "can"):
                    detected_materials.extend(["Tin", "Metal"])
                elif container_type == "bottle" and "glass" in full_text:
                    detected_materials.append("Glass")
                elif container_type in ("box", "carton"):
                    detected_materials.append("Cardboard")

            for mat in self.KNOWN_MATERIALS:
                if re.search(rf"\b{re.escape(mat)}\b", full_text):
                    title_mat = mat.title()
                    if title_mat not in detected_materials:
                        detected_materials.append(title_mat)

        # 5. Generate Descriptive Style / Product Tags
        style_tags: List[str] = []
        if is_packaged_container and container_type:
            style_tags.append(f"{container_type.title()} Packaging")
        if category == "Food & Beverage":
            style_tags.extend(["Ready To Eat", "Food Grade", "Packaged Food"])
        elif category == "Beauty & Personal Care":
            style_tags.extend(["Personal Care", "Daily Routine", "Dermatological"])
        elif category == "Office Supplies & Stationery":
            style_tags.extend(["Office Supplies", "Printing Paper", "Jam Free"])
        elif category == "Electronics":
            style_tags.extend(["Wireless", "Tech Accessory"])
        elif category == "Apparel & Fashion":
            style_tags.extend(["Casual Wear", "Apparel"])

        for tag in ["minimalist", "modern", "vintage", "premium", "compact", "ergonomic"]:
            if tag in full_text and tag.title() not in style_tags:
                style_tags.append(tag.title())

        # Fill with top colors/materials if few tags
        for c in detected_colors[:2]:
            if c not in style_tags:
                style_tags.append(c)

        return ProductVisualAttributes(
            category=category,
            product_type=product_type,
            dominant_colors=detected_colors,
            detected_text=detected_text,
            materials=detected_materials,
            style_tags=style_tags[:6],
            detailed_description=detailed_caption,
            raw_vlm_outputs=raw_outputs,
        )

    def _detect_container(self, caption: str, ocr_text: str) -> Tuple[bool, str]:
        """Detect whether the subject is a packaged item (can, tin, box, jar, etc.)."""
        for container in self.CONTAINER_KEYWORDS:
            pattern = rf"\b{re.escape(container)}\b"
            if re.search(pattern, caption) or re.search(pattern, ocr_text):
                return True, container

        # Check for weight / volume markings in OCR indicating packaging (e.g., '1kg', '500g', '100ml')
        if re.search(r'\b\d+\s*(?:g|gm|gms|kg|ml|fl\s*oz|l|litre|litres|pcs|units)\b', ocr_text):
            return True, "package"

        return False, ""

    @classmethod
    def _tokenize_whole_words(cls, text: str) -> List[str]:
        """Extract lowercase whole word tokens, preserving hyphens (e.g. t-shirt)."""
        return re.findall(r'\b[a-z0-9]+(?:-[a-z0-9]+)*\b', text.lower())

    def _check_priority_registry(self, ocr_normalized: str, ocr_tokens: List[str]) -> Optional[Dict[str, Any]]:
        """Layer 1: Showcase Priority Registry brand/product lookup on normalized OCR text."""
        for entry in self.SHOWCASE_PRIORITY_REGISTRY:
            for pattern in entry["regexes"]:
                if re.search(pattern, ocr_normalized, re.IGNORECASE):
                    return entry
        return None

    def _classify_with_weighted_scoring(
        self,
        ocr_tokens: List[str],
        caption_tokens: List[str],
        is_container: bool,
        container_type: str,
    ) -> Tuple[Optional[str], Optional[str], List[str]]:
        """Layer 2: Word-tokenized weighted scoring across categories (No naive substring matching)."""
        scores: Dict[str, int] = {}
        matched_words_by_category: Dict[str, set] = {}

        for category, config in self.LAYER2_CATEGORY_KEYWORDS.items():
            kw_set = config["keywords"]
            # OCR tokens are ground-truth product text (weighted 2x)
            ocr_matches = set(w for w in ocr_tokens if w in kw_set)

            # Caption tokens: if subject is a physical packaging container (tin, can, box, jar),
            # ignore accidental apparel words in caption artwork
            if category == "Apparel & Fashion" and is_container:
                caption_matches = set()
            else:
                caption_matches = set(w for w in caption_tokens if w in kw_set)

            total_unique_matches = ocr_matches | caption_matches
            # Weighted score: OCR matches weighted 2x, caption matches 1x
            score = (len(ocr_matches) * 2) + len(caption_matches)

            scores[category] = score
            matched_words_by_category[category] = total_unique_matches

        # Sort categories by score descending, then by total unique matched words
        sorted_categories = sorted(
            scores.items(),
            key=lambda x: (x[1], len(matched_words_by_category[x[0]])),
            reverse=True,
        )

        top_cat, top_score = sorted_categories[0]
        if top_score == 0:
            return None, None, []

        top_words = matched_words_by_category[top_cat]
        product_type = self._determine_layer2_product_type(top_cat, top_words, container_type)
        materials = self._determine_layer2_materials(top_cat, top_words, container_type)

        return top_cat, product_type, materials

    @staticmethod
    def _determine_layer2_product_type(category: str, matched_words: set, container_type: str) -> str:
        """Map matched Layer 2 keywords to professional product type."""
        if category == "Beauty & Personal Care":
            if matched_words & {"cleanser", "cleansers", "wash", "washes"}:
                return "Gentle Skin Cleanser / Face Wash"
            if matched_words & {"serum", "serums"}:
                return "Dropper Bottle Serum"
            if matched_words & {"lotion", "lotions"}:
                return "Body Lotion"
            if matched_words & {"cream", "creams"}:
                return "Moisturizing Face Cream"
            if "spf" in matched_words:
                return "Daily Sunscreen Lotion"
            return "Personal Care Product"

        if category == "Food & Beverage":
            if matched_words & {"malt", "drink", "drinks", "nutrition"}:
                return "Malted Health Nutrition Drink Mix / Jar"
            if matched_words & {"sweet", "sweets", "syrup", "syrups"}:
                if container_type in ("tin", "can"):
                    return "Canned Traditional Sweets / Rasgulla Tin"
                return "Traditional Sweets Confectionery"
            if matched_words & {"chocolate", "chocolates"}:
                return "Chocolate Confectionery"
            if matched_words & {"snack", "snacks"}:
                return "Packaged Savory Snack"
            if matched_words & {"tea", "coffee"}:
                return "Beverage Mix"
            return "Packaged Food"

        if category == "Office Supplies & Stationery":
            if matched_words & {"paper", "papers", "ream", "reams", "a4", "sheet", "sheets", "gsm"}:
                return "A4 Copier Paper Ream / Notebook"
            if matched_words & {"notebook", "notebooks"}:
                return "Office Notebook"
            if matched_words & {"print", "printing", "ink", "inks"}:
                return "Printing Supplies"
            return "Office Supplies & Stationery"

        if category == "Apparel & Fashion":
            if matched_words & {"t-shirt", "tshirt", "t-shirts", "shirt", "shirts"}:
                return "T-Shirt"
            if "pants" in matched_words:
                return "Trousers"
            if matched_words & {"dress", "dresses"}:
                return "Dress"
            return "Apparel"

        return "Product"

    @staticmethod
    def _determine_layer2_materials(category: str, matched_words: set, container_type: str) -> List[str]:
        """Infer default materials from category and container geometry."""
        if category == "Beauty & Personal Care":
            if container_type == "bottle":
                return ["Plastic Bottle with Pump Dispenser"]
            if container_type == "jar":
                return ["Cosmetic Jar"]
            return ["Plastic Bottle with Pump Dispenser"]

        if category == "Food & Beverage":
            if container_type in ("tin", "can"):
                return ["Food-Grade Tin Can"]
            if container_type == "jar":
                return ["Food-Grade Plastic Jar"]
            return ["Food-Grade Packaging"]

        if category == "Office Supplies & Stationery":
            return ["Wood-Free Paper"]

        if category == "Apparel & Fashion":
            if "cotton" in matched_words:
                return ["100% Combed Cotton"]
            return ["Cotton", "Fabric"]

        return []

    def _classify_category_and_type(
        self,
        ocr_text: str,
        caption: str,
        is_container: bool,
        container_type: str,
    ) -> Tuple[str, str, List[str]]:
        """Classify Category, Product Type, and Materials using Layer 1 (Priority) and Layer 2 (Weighted Scoring)."""
        ocr_normalized = re.sub(r'[^a-z0-9\-]+', ' ', ocr_text.lower()).strip()
        ocr_tokens = self._tokenize_whole_words(ocr_normalized)

        # -------------------------------------------------------------
        # LAYER 1: Showcase Priority Registry (Immediate OCR Lookup)
        # -------------------------------------------------------------
        priority_match = self._check_priority_registry(ocr_normalized, ocr_tokens)
        if priority_match:
            logger.info(f"Layer 1 Showcase Priority matched: {priority_match['id']} -> {priority_match['category']}")
            return (
                priority_match["category"],
                priority_match["product_type"],
                list(priority_match.get("materials", [])),
            )

        # -------------------------------------------------------------
        # LAYER 2: Word-Tokenized Weighted Scoring for New/Unseen Products
        # -------------------------------------------------------------
        sanitized_caption = self._remove_person_descriptions(caption)
        caption_normalized = re.sub(r'[^a-z0-9\-]+', ' ', sanitized_caption.lower()).strip()
        caption_tokens = self._tokenize_whole_words(caption_normalized)

        l2_category, l2_product_type, l2_materials = self._classify_with_weighted_scoring(
            ocr_tokens=ocr_tokens,
            caption_tokens=caption_tokens,
            is_container=is_container,
            container_type=container_type,
        )

        if l2_category:
            logger.info(f"Layer 2 Weighted Scoring matched: {l2_category} ({l2_product_type})")
            return l2_category, l2_product_type, l2_materials

        # -------------------------------------------------------------
        # Fallback: General Merchandise
        # -------------------------------------------------------------
        if is_container and container_type:
            if container_type in ("tin", "can"):
                return "Food & Beverage", f"Canned {container_type.title()} Product", ["Food-Grade Tin Can"]
            if container_type in ("box", "carton"):
                return "General Merchandise", f"Packaged {container_type.title()}", ["Cardboard Box"]
            if container_type == "jar":
                return "General Merchandise", "Packaged Jar", ["Food-Grade Plastic Jar"]
            if container_type == "bottle":
                return "General Merchandise", "Bottle", ["Plastic Bottle"]

        return "General Merchandise", "Product", []

    @staticmethod
    def _remove_person_descriptions(caption: str) -> str:
        """Strip descriptions of people/characters pictured on labels to prevent misclassification."""
        # Patterns like 'man wearing a red kurta', 'woman in yellow dress', 'person with black shirt'
        cleaned = re.sub(
            r'\b(?:man|woman|person|model|actor|boy|girl)\s+(?:wearing|in|dressed in|with)\s+[^,\.]+',
            '',
            caption,
            flags=re.IGNORECASE,
        )
        # Patterns like 'photo of a man...', 'picture of a woman...'
        cleaned = re.sub(
            r'\b(?:photo|picture|illustration|graphic|image)\s+of\s+(?:a\s+)?(?:man|woman|person|chef|actor)[^,\.]*',
            '',
            cleaned,
            flags=re.IGNORECASE,
        )
        return cleaned

    @staticmethod
    def _format_food_product_type(keyword: str, container_type: str) -> str:
        """Format an accurate, professional product type for food items."""
        kw_title = keyword.title()
        if keyword in ("rasgulla", "gulab jamun", "cham cham", "rajbhog"):
            if container_type in ("tin", "can"):
                return f"{kw_title} Tin"
            return f"{kw_title} Sweets"
        elif keyword in ("namkeen", "bhujia", "sev", "mixture"):
            return f"{kw_title} Snack Pack"
        elif keyword in ("bournvita", "horlicks", "boost", "complan"):
            return "Nutritional Health Drink Mix"
        elif container_type:
            return f"{kw_title} {container_type.title()}"
        return kw_title
