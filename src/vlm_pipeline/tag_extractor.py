class ProductVisualAttributes(BaseModel):
    """Structured e-commerce visual attributes parsed from Florence-2 VLM."""

    category: str = Field(
        default="General Merchandise",
        description="Primary e-commerce product category.",
    )
    product_type: str = Field(
        default="Product",
        description="Specific item type (e.g., Rasgulla Tin, Face Serum, Running Shoes).",
    )
    dominant_colors: List[str] = Field(
        default_factory=list,
        description="Extracted primary and accent color names.",
    )
    detected_text: List[str] = Field(
        default_factory=list,
        description="Brand names, labels, and text detected via OCR.",
    )
    materials: List[str] = Field(
        default_factory=list,
        description="Detected materials and surface finishes (e.g., Tin/Metal, Glass, Plastic, Cotton).",
    )
    style_tags: List[str] = Field(
        default_factory=list,
        description="Descriptive tags (e.g., Packaged Sweet, Traditional, Minimalist, Modern).",
    )
    detailed_description: str = Field(
        default="",
        description="Exhaustive visual caption generated by Florence-2.",
    )
    raw_vlm_outputs: Dict[str, Any] = Field(
        default_factory=dict,
        description="Raw task dictionary outputs from Florence-2 inference.",
    )


