"""Florence-2 Vision-Language Model inference client using Hugging Face Transformers."""

from __future__ import annotations

import logging
from typing import Any, Dict, Optional, Union
from pathlib import Path
from PIL import Image
import torch
from transformers import AutoModelForCausalLM, AutoProcessor
import transformers.dynamic_module_utils

import importlib

# Patch dynamic module import check so flash_attn (optional dependency) doesn't block CPU/Windows loading
def _patched_check_imports(filename: str) -> list[str]:
    imports = transformers.dynamic_module_utils.get_imports(filename)
    missing = []
    for imp in imports:
        if imp == "flash_attn":
            continue
        try:
            importlib.import_module(imp)
        except ImportError:
            missing.append(imp)
    if missing:
        raise ImportError(
            f"This modeling file requires the following packages that were not found in your environment: {', '.join(missing)}."
        )
    return transformers.dynamic_module_utils.get_relative_imports(filename)


transformers.dynamic_module_utils.check_imports = _patched_check_imports

logger = logging.getLogger(__name__)


class FlorenceClient:
    """Wrapper for Microsoft Florence-2 Vision-Language Model inference."""

    TASK_CAPTION = "<CAPTION>"
    TASK_DETAILED_CAPTION = "<DETAILED_CAPTION>"
    TASK_MORE_DETAILED_CAPTION = "<MORE_DETAILED_CAPTION>"
    TASK_OCR = "<OCR>"
    TASK_OCR_WITH_REGION = "<OCR_WITH_REGION>"
    TASK_OD = "<OD>"
    TASK_DENSE_REGION_CAPTION = "<DENSE_REGION_CAPTION>"

    def __init__(
        self,
        model_id: str = "microsoft/Florence-2-base",
        device: Optional[str] = None,
        torch_dtype: Optional[torch.dtype] = None,
    ) -> None:
        """Initialize Florence-2 client with automatic device and precision detection.
        
        Args:
            model_id: HuggingFace repository ID (default: 'microsoft/Florence-2-base').
            device: 'cuda', 'cpu', or None (auto-detected).
            torch_dtype: PyTorch data type (float16 for CUDA, float32 for CPU).
        """
        self.model_id = model_id

        if device is None:
            self.device = "cuda" if torch.cuda.is_available() else "cpu"
        else:
            self.device = device

        if torch_dtype is None:
            self.torch_dtype = torch.float16 if self.device == "cuda" else torch.float32
        else:
            self.torch_dtype = torch_dtype

        logger.info(f"Loading Florence-2 model '{model_id}' on device: {self.device} ({self.torch_dtype})")

        self.model = AutoModelForCausalLM.from_pretrained(
            self.model_id,
            torch_dtype=self.torch_dtype,
            trust_remote_code=True,
        ).to(self.device).eval()

        self.processor = AutoProcessor.from_pretrained(
            self.model_id,
            trust_remote_code=True,
        )

    def run_task(
        self,
        image: Union[str, Path, Image.Image],
        task_prompt: str,
        text_input: Optional[str] = None,
        max_new_tokens: int = 1024,
        num_beams: int = 3,
    ) -> Dict[str, Any]:
        """Run a single vision-language prompt task on an image.
        
        Args:
            image: Image file path or PIL Image.
            task_prompt: Task token such as '<MORE_DETAILED_CAPTION>', '<OCR>', or '<OD>'.
            text_input: Optional additional textual query for the prompt.
            max_new_tokens: Maximum tokens for text generation.
            num_beams: Beam search size.
            
        Returns:
            Parsed dictionary response generated by the Florence-2 processor.
        """
        if isinstance(image, (str, Path)):
            pil_image = Image.open(image).convert("RGB")
        elif isinstance(image, Image.Image):
            pil_image = image.convert("RGB")
        else:
            raise ValueError(f"Unsupported image type: {type(image)}")

        full_prompt = task_prompt if text_input is None else f"{task_prompt} {text_input}"

        inputs = self.processor(
            text=full_prompt,
            images=pil_image,
            return_tensors="pt",
        )

        # Move tensors to active device
        inputs = {k: v.to(self.device) if isinstance(v, torch.Tensor) else v for k, v in inputs.items()}
        if "pixel_values" in inputs and inputs["pixel_values"].dtype != self.torch_dtype:
            inputs["pixel_values"] = inputs["pixel_values"].to(self.torch_dtype)

        with torch.no_grad():
            generated_ids = self.model.generate(
                input_ids=inputs["input_ids"],
                pixel_values=inputs["pixel_values"],
                max_new_tokens=max_new_tokens,
                num_beams=num_beams,
                do_sample=False,
            )

        generated_text = self.processor.batch_decode(generated_ids, skip_special_tokens=False)[0]

        parsed_answer = self.processor.post_process_generation(
            generated_text,
            task=task_prompt,
            image_size=(pil_image.width, pil_image.height),
        )

        return parsed_answer
